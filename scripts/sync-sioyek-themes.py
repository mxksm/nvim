#!/usr/bin/env python3
"""Import Sioyek's theme catalog; Neovim remains usable without Sioyek installed."""
import argparse
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--source", type=Path, default=root.parent / "sioyek/themes")
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
catalog = []
for path in sorted(args.source.glob("*.config")):
    text = path.read_text()
    name = re.search(r"^# name: (.+)$", text, re.M).group(1)
    colors = dict(re.findall(r"^(\w+)\s+(#[\da-fA-F]{6})\b", text, re.M))
    catalog.append(dict(id=path.stem, name=name, colors=colors))
assert catalog, "No Sioyek themes found"
out = "-- Generated by scripts/sync-sioyek-themes.py; edit Sioyek's themes instead.\nreturn vim.json.decode([=[\n"
out += json.dumps(catalog, ensure_ascii=False, indent=2) + "\n]=])\n"
dest = root / "lua/configs/sioyek_palettes.lua"
if args.check:
    assert dest.read_text() == out, "Theme catalog differs; run scripts/sync-sioyek-themes.py"
else:
    dest.write_text(out)
print(f"{len(catalog)} Sioyek themes {'verified' if args.check else 'imported'}")
